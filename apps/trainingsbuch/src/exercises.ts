/** How the amount of an exercise is counted. */
export const UNITS = ["reps", "m", "cal", "s"] as const;
export type Unit = (typeof UNITS)[number];

/** German labels of the units, for inputs ("Wiederholungen") and for text ("21 ×"). */
export const UNIT_LABELS: Record<Unit, { input: string; short: string }> = {
  reps: { input: "Wiederholungen", short: "×" },
  m: { input: "Meter", short: "m" },
  cal: { input: "Kalorien", short: "cal" },
  s: { input: "Sekunden", short: "s" },
};

/** The units of the exercises that are not counted in reps. The first unit is the default. */
const OTHER_UNITS: Partial<Record<ExerciseId, readonly Unit[]>> = {
  run: ["m"],
  row: ["m", "cal"],
  bike: ["cal", "m"],
  "air-bike": ["cal", "m"],
  ski: ["m", "cal"],
  "handstand-walk": ["m"],
  "l-sit": ["s"],
  "shuttle-run": ["m"],
  handstand: ["s"],
};

/** The units that make sense for an exercise. The first unit is the default. */
export function unitsOf(exercise: ExerciseId): readonly Unit[] {
  return OTHER_UNITS[exercise] ?? ["reps"];
}

